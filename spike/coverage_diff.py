#!/usr/bin/env python3
"""Phase 1 step 1: coverage diff between the web scrape list and the Subsonic list.

Scrape side  = Bandcamp's own fan-collection feed, read exactly the way fetch.py reads it
               (collection page blob + /api/fancollection/1/collection_items), deduplicated by
               (type, id). Uses the cookie jar already imported to ~/.cache/omatimeatbandcamp/.
Subsonic side = getAlbumList2, paged.
Both are keyed by backend.textnorm.album_key(artist, title).

Writes/replaces the "Addendum A" section of spike/SUBSONIC-REPORT.md. Read-only against both services.
"""
import collections
import json
import os
import sys
import time
import urllib.error
import urllib.request
from datetime import datetime, timezone

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, ROOT)
import fetch  # noqa: E402
from backend.subsonic import Client  # noqa: E402
from backend.textnorm import album_key, clean, norm  # noqa: E402

REPORT = os.path.join(HERE, "SUBSONIC-REPORT.md")
MARK = "<!-- addendum-a -->"
COOKIES = os.path.expanduser("~/.cache/omatimeatbandcamp/cookies.txt")
OUT = []


def w(s=""):
    OUT.append(s)
    print(s, flush=True)


def parse_dt(s):
    return datetime.strptime(s, "%d %b %Y %H:%M:%S GMT")


def web_feed():
    ck = fetch.load_cookie(COOKIES)
    acct = fetch.resolve_account(ck)
    blob = fetch.page_blob(acct["url"], ck)
    fan_id = blob["fan_data"]["fan_id"]
    cd = blob["collection_data"]
    raw = list(blob["item_cache"]["collection"].values())
    token = cd["last_token"]
    while token:
        d = fetch.get_json("https://bandcamp.com/api/fancollection/1/collection_items", ck,
                           {"fan_id": fan_id, "older_than_token": token, "count": 100})
        if not d or not d.get("items"):
            break
        raw += d["items"]
        token = d.get("last_token")
        if not d.get("more_available"):
            break
        time.sleep(0.1)
    uniq = {}
    for v in raw:
        uniq.setdefault((v.get("tralbum_type"), str(v.get("tralbum_id"))), v)
    return list(uniq.values()), len(raw), cd.get("item_count")


def probe_stream(c, track_id):
    req = urllib.request.Request(c.stream_url(track_id), headers={"Range": "bytes=0-1023"})
    try:
        with urllib.request.urlopen(req, timeout=30) as r:
            return r.status in (200, 206) and (r.headers.get("content-type") or "").startswith("audio/") and len(r.read(1024)) > 0
    except (urllib.error.URLError, OSError):
        return False


def main():
    started = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    scrape, raw_n, page_count = web_feed()
    cache = json.load(open(os.path.expanduser("~/.cache/omatimeatbandcamp/collection.json")))["items"]
    c = Client()
    sub = c.albums()

    S = collections.defaultdict(list)
    for v in scrape:
        S[album_key(v["band_name"], v["item_title"])].append(v)
    U = collections.defaultdict(list)
    for a in sub:
        U[album_key(a["artist"], a["name"])].append(a)
    both, s_only, u_only = set(S) & set(U), set(S) - set(U), set(U) - set(S)
    types = collections.Counter(v["tralbum_type"] for v in scrape)

    w(MARK)
    w("## Addendum A: coverage diff, web scrape list vs Subsonic list (Phase 1, step 1)\n")
    w(f"Generated by `spike/coverage_diff.py` on {started}. Read-only against both services.\n")
    w("**Matching key**: `norm(artist) | norm(title)`, where `norm` decodes HTML entities (repeatedly), "
      "decomposes accents and drops combining marks, casefolds, turns `&` into `and`, and collapses every run of "
      "punctuation/whitespace to one space (`backend/textnorm.py`).\n")
    w("### Counts\n")
    w("| | items | distinct keys |\n|---|---|---|")
    w(f"| Web scrape list (collection feed, de-duplicated by type+id) | {len(scrape)} "
      f"({types.get('a', 0)} albums + {types.get('t', 0)} single tracks) | {len(S)} |")
    w(f"| Subsonic `getAlbumList2` | {len(sub)} | {len(U)} |")
    w(f"| Key present in both | | {len(both)} |")
    w(f"| Scrape only | | {len(s_only)} |")
    w(f"| Subsonic only | | {len(u_only)} |")
    w(f"\n- The scrape list measured now equals the cached `collection.json` that gave the original 645: "
      f"{len(scrape)} vs {len(cache)} items. The raw feed returned {raw_n} rows, i.e. it repeats items across "
      f"pages, so it is de-duplicated by (type, id) exactly as fetch.py does. The collection page header claims `item_count` = {page_count}, "
      f"which does not match what the feed enumerates.")
    dups = {k: len(v) for k, v in S.items() if len(v) > 1}
    udups = {k: len(v) for k, v in U.items() if len(v) > 1}
    w(f"- Keys occurring more than once: scrape {dups}, Subsonic {udups} "
      "(two entries share one key on both sides; whether they are two editions or a true duplicate is not checked "
      "here; matching must pair within a key rather than assume uniqueness).")
    w(f"- Reconciliation: {len(sub)} - {len(scrape)} = {len(sub) - len(scrape):+d}  =  "
      f"(Subsonic-only {len(u_only)}) - (scrape-only {len(s_only)}) = {len(u_only) - len(s_only):+d}.\n")

    # Subsonic created vs scrape purchased
    diffs = []
    for k in both:
        for a, v in zip(U[k], S[k]):
            if a.get("created") and v.get("purchased"):
                diffs.append(abs((parse_dt(a["created"]) - parse_dt(v["purchased"])).total_seconds()))
    w(f"- Calibration: for the {len(diffs)} matched albums that carry both dates, Subsonic `created` equals the web "
      f"feed's `purchased` to within 60 s for {sum(1 for d in diffs if d < 60)} of them, so `created` is the "
      "purchase/collect time.\n")

    # classify scrape-only
    sub_only_albums = [a for k in u_only for a in U[k]]
    songs = {}
    for a in sub_only_albums:
        for s in c.album(a["id"]).get("song") or []:
            songs.setdefault(norm(s["title"]), (a["id"], a["name"]))
    w("### Scrape only (in the web list, not in Subsonic)\n")
    w("| type | artist | title | class | Subsonic album that contains it |\n|---|---|---|---|---|")
    claimed = set()
    for k in sorted(s_only):
        for v in S[k]:
            kind = "single track" if v["tralbum_type"] == "t" else "album"
            hit = songs.get(norm(v["item_title"])) if kind == "single track" else None
            if hit:
                claimed.add(hit[0])
                cls = "single-track purchase; Subsonic lists its parent album"
            elif v.get("is_preorder"):
                cls = "PRE-ORDER (`is_preorder` true); absent from Subsonic"
            else:
                cls = "unexplained"
            w(f"| {kind} | {clean(v['band_name'])} | {clean(v['item_title'])} | {cls} | "
              f"{hit[1] + ' (' + hit[0] + ')' if hit else ''} |")

    # classify subsonic-only
    unclaimed = [a for a in sub_only_albums if a["id"] not in claimed]
    ts = collections.Counter(a["created"] for a in unclaimed if a.get("created"))
    bulk_ts = {t for t, n in ts.items() if n >= 10}
    groups = {"parent": [], "bulk": [], "other": []}
    for a in sorted(sub_only_albums, key=lambda x: (x["artist"], x["name"])):
        if a["id"] in claimed:
            groups["parent"].append(a)
        elif a.get("created") in bulk_ts:
            groups["bulk"].append(a)
        else:
            groups["other"].append(a)

    w(f"\n### Subsonic only ({len(u_only)} albums)\n")
    w(f"**Group 1: parent albums of the single-track purchases: {len(groups['parent'])} albums.** "
      "None has a `created` date. Each is an album of which only the purchased track(s) are in the collection "
      "(songCount equals the number of scrape-side single tracks matched to it).\n")
    w("| id | artist | album | songCount | scrape single tracks matched |\n|---|---|---|---|---|")
    for a in groups["parent"]:
        n = sum(1 for k in s_only for v in S[k] if v["tralbum_type"] == "t"
                and songs.get(norm(v["item_title"]), (None,))[0] == a["id"])
        w(f"| {a['id']} | {clean(a['artist'])} | {clean(a['name'])} | {a.get('songCount')} | {n} |")
    stamp = collections.Counter(a.get("created") for a in groups["bulk"]).most_common(1)
    w(f"\n**Group 2: one bulk purchase timestamp: {len(groups['bulk'])} albums"
      + (f", {stamp[0][1]} of them created at exactly `{stamp[0][0]}`" if stamp else "") + ".**\n")
    w("| artist | albums |\n|---|---|")
    for art, n in collections.Counter(clean(a["artist"]) for a in groups["bulk"]).most_common():
        w(f"| {art} | {n} |")
    w("\nExamples: " + "; ".join(f"{clean(a['artist'])} - {clean(a['name'])} ({a.get('songCount')} tracks)"
                                  for a in groups["bulk"][:6]) + ".")
    w(f"\n**Group 3: other Subsonic-only albums: {len(groups['other'])}.**\n")
    w("| id | artist | album | songCount | created |\n|---|---|---|---|---|")
    for a in groups["other"]:
        w(f"| {a['id']} | {clean(a['artist'])} | {clean(a['name'])} | {a.get('songCount')} | {a.get('created')} |")

    # evidence
    purchased = sorted(parse_dt(v["purchased"]) for v in scrape if v.get("purchased"))
    near = []
    for a in groups["other"]:
        if a.get("created"):
            t = parse_dt(a["created"])
            near.append(sum(1 for p in purchased if abs((p - t).total_seconds()) < 3600))
    macro = [a for a in groups["bulk"]]
    in_feed = sum(1 for v in scrape if clean(v["band_name"]) in {clean(a["artist"]) for a in macro})
    w("\n### Evidence\n")
    w(f"1. Web feed items whose artist is one of the Group 2 artists: **{in_feed}**. The feed lists none of them.")
    w("2. For each Group 3 album, the number of *other* purchases in the web feed within +/-1 h of its `created` time: "
      f"{near}. For the {sum(1 for n in near if n)} albums with neighbours, the surrounding purchases are in the feed "
      "and the album is not, i.e. it was dropped from the middle of a run. The remaining album(s) have no neighbours "
      "so this check says nothing about them.")
    tested = groups["bulk"] + groups["other"]
    ok = 0
    for a in tested:
        songs_a = c.album(a["id"]).get("song") or []
        if songs_a and probe_stream(c, songs_a[0]["id"]):
            ok += 1
    w(f"3. Stream probe (Range request on track 1) of the {len(tested)} Group 2 + Group 3 albums: "
      f"**{ok} of {len(tested)} streamable** via Subsonic. They are playable, not dead entries.")
    w("4. Manual observation, 2026-10-23 (not produced by this script): `https://macroblank.bandcamp.com/music`, fetched "
      "with the session cookie, is an empty placeholder page (\"Seattle, Washington\", link to Patreon) listing no releases.")
    pre = [v for v in scrape if v.get("is_preorder")]
    w(f"5. Web feed items with `is_preorder` true: {len(pre)} -> "
      + "; ".join(f"{clean(v['band_name'])} - {clean(v['item_title'])} (`num_streamable_tracks` = {v.get('num_streamable_tracks')})" for v in pre)
      + ". It has no Subsonic counterpart under any normalised key (searched in Section 4 above too).")

    w("\n### Reconciliation and best explanation\n")
    g1, g2, g3 = len(groups["parent"]), len(groups["bulk"]), len(groups["other"])
    n_single = sum(1 for k in s_only for v in S[k] if v["tralbum_type"] == "t")
    n_pre = sum(1 for k in s_only for v in S[k] if v["tralbum_type"] == "a")
    w(f"- Subsonic has {g2} + {g3} = **{g2 + g3} albums the web feed does not list at all**.")
    w(f"- The web list has {n_single} single-track items that Subsonic folds into {g1} parent albums "
      f"(**{n_single - g1} fewer** albums in Subsonic).")
    w(f"- The web list has {n_pre} pre-order album Subsonic does not have (**{n_pre} fewer**).")
    w(f"- Net: {g2 + g3} - {n_single - g1} - {n_pre} = **{g2 + g3 - (n_single - g1) - n_pre:+d}**, which is the "
      f"{len(sub) - len(scrape):+d} gap (645 -> 687).")
    w("\nBest explanation, in order of confidence:\n")
    w(f"1. **High confidence, measured.** The gap is not noise or double counting. Of the {len(sub)} Subsonic albums, "
      f"{len(both)} correspond one-to-one to web items, and every other difference is accounted for above.")
    w(f"2. **Single-track purchases** ({n_single} web items) appear in Subsonic as their *parent album* containing just "
      "the purchased track(s). Same ownership, different shape; this shrinks the Subsonic count by "
      f"{n_single - g1}. Single tracks must be matched by track title inside a Subsonic album, not by album key.")
    w(f"3. **Collected items that Bandcamp's web collection feed no longer lists** ({g2 + g3} albums). "
      "Subsonic still lists and streams them. Likeliest cause: the artist/label removed or hid the public pages "
      "(for the bulk group the artist's page is an empty placeholder), and the web feed omits items whose pages are "
      "gone while the Subsonic server does not. That cause is an inference from items 1-4 above; the API data "
      "does not state it directly.")
    w("4. **Pre-orders are invisible to Subsonic**: the one pre-order in the collection exists only in the web data, "
      "which is why web data must stay in the hybrid for pre-order display.")

    block = "\n".join(OUT) + "\n"
    cur = open(REPORT).read()
    if MARK in cur:
        cur = cur[:cur.index(MARK)].rstrip() + "\n\n"
    else:
        cur = cur.rstrip() + "\n\n"
    open(REPORT, "w").write(cur + block)
    print(f"\nupdated {REPORT}")


if __name__ == "__main__":
    main()
