#!/usr/bin/env python3
"""Phase 1 results: runs the real backend end to end and writes "Addendum B" of SUBSONIC-REPORT.md.

Measures a cold sync and an incremental sync into a throw-away cache directory (the plugin's real cache is
not touched), then checks the fixtures and the honesty rules against the resulting library.
"""
import collections
import json
import os
import re
import subprocess
import sys
import tempfile
import time
import urllib.error
import urllib.request
from datetime import datetime, timezone

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, ROOT)
from backend import bandcamp as bc  # noqa: E402
from backend.library import COOKIES, Library  # noqa: E402
from backend.subsonic import Client  # noqa: E402

REPORT = os.path.join(HERE, "SUBSONIC-REPORT.md")
MARK = "<!-- addendum-b -->"
FI_URL = "https://shamekfarrah.bandcamp.com/album/first-impressions-deluxe-edition"
FI_ID = 2025444064
ENTITY = re.compile(r"&(?:[a-zA-Z]+|#[0-9]+|#x[0-9a-fA-F]+);")
OUT = []


def w(s=""):
    OUT.append(s)
    print(s, flush=True)


def probe(url):
    req = urllib.request.Request(url, headers={"Range": "bytes=0-1023", "User-Agent": bc.UA})
    try:
        with urllib.request.urlopen(req, timeout=30) as r:
            data = r.read(1024)
            return r.status, (r.headers.get("content-type") or ""), len(data), r.headers.get("content-range", "").rsplit("/", 1)[-1]
    except urllib.error.HTTPError as e:
        return e.code, "", 0, ""
    except OSError as e:
        return type(e).__name__, "", 0, ""


def main():
    started = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    sub = Client()
    cookie = bc.load_cookie(COOKIES)
    tmp = tempfile.mkdtemp(prefix="omatime-phase1-")
    cache = os.path.join(tmp, "library")

    w(MARK)
    w("## Addendum B: Phase 1 results (backend data model, client, matching, background sync)\n")
    w(f"Generated by `spike/phase1_results.py` on {started}. Cold and incremental syncs below were run into a "
      "temporary cache directory with the production code path (`backend.library.Library.sync`, 4 workers).\n")

    # --- sync timings
    lib = Library(cache_dir=cache, subsonic=sub)
    t0 = time.perf_counter()
    stages = []
    lib.sync(workers=4, progress=lambda st, d, n: stages.append((st, d, n, time.perf_counter() - t0)))
    cold = time.perf_counter() - t0
    cold_meta = json.loads(json.dumps(lib.meta))
    usable_at = next(t for s, d, n, t in stages if s == "playlists")
    lib2 = Library(cache_dir=cache, subsonic=Client())
    t1 = time.perf_counter()
    lib2.load()
    load_s = time.perf_counter() - t1
    size = os.path.getsize(os.path.join(cache, "library.json"))
    t2 = time.perf_counter()
    lib2.sync(workers=4)
    inc = time.perf_counter() - t2
    inc_meta = lib2.meta

    def tm(meta, k):
        return meta["timings"].get(k, "-")

    w("### Sync timings (wall clock)\n")
    w("| | cold sync (empty cache) | incremental sync (cache present) |\n|---|---|---|")
    w(f"| total | **{cold:.1f} s** | **{inc:.1f} s** |")
    for label, k in (("album lists (web feed + getAlbumList2)", "album_lists_s"),
                     ("matching (incl. parent-album lookups)", "matching_s"),
                     ("playlists (getPlaylists + getPlaylist per playlist)", "playlists_s"),
                     ("per-album tracklists (getAlbum, 4 workers)", "tracklists_s")):
        w(f"| {label} | {tm(cold_meta, k)} s | {tm(inc_meta, k)} s |")
    w(f"| tracklists fetched | {tm(cold_meta, 'tracklists_fetched')} | {tm(inc_meta, 'tracklists_fetched')} |")
    w(f"\n- UI start-up path: `Library.load()` from the cache file ({size / 1e6:.2f} MB) took **{load_s * 1000:.0f} ms** "
      "and makes no network calls. The sync runs on its own thread/process and writes `status.json` and the cache after every "
      "stage, so nothing in the UI path waits on it.")
    w(f"- During the cold sync the matched library was published and saved at about {usable_at:.1f} s; the remaining "
      f"{cold - usable_at:.1f} s is playlists, pre-order pages and tracklists.")
    w("- Why the album-list stage is slow: the web feed is read sequentially in pages that each return ~100 rows of which ~20 are new "
      "(2908 rows for 645 unique items), so ~30 sequential requests are needed. Subsonic's own album list takes under a second.")
    fails = tm(cold_meta, "tracklist_failures")
    w(f"- Tracklist failures in the cold sync: {len(fails) if isinstance(fails, list) else fails}.")

    # --- match coverage
    rep = lib.report
    w("\n### Match coverage (logged by every sync to `sync.log` and stored in the cache)\n")
    w("```\n" + rep["summary"] + "\n```")
    w("\n| | count |\n|---|---|")
    for k in ("web_items", "subsonic_albums", "matched_by_key", "duplicate_keys_paired", "single_items_matched_by_track",
              "single_parent_albums", "merged_albums"):
        w(f"| {k} | {rep[k]} |")
    w(f"| web-only albums | {len(rep['web_only'])} ({', '.join(x['artist'] + ' - ' + x['title'] for x in rep['web_only'])}) |")
    w(f"| unresolved single tracks | {len(rep['unresolved_singles'])} |")
    w(f"| Subsonic-only albums | {len(rep['subsonic_only'])} |")
    w(f"\nWeb coverage: **{rep['web_coverage_pct']}%** ({rep['matched_by_key'] + rep['single_items_matched_by_track']} of {rep['web_items']}). "
      "Cross-check with Addendum A: there, 627 distinct keys matched on album key alone. Here the 36 single-track web items are matched "
      "as singles (by track title inside the Subsonic album). The difference is consistent with 20 of the 36 single-track items "
      "(36 minus the 16 that Addendum A found unmatched) having a Subsonic album with the same artist and title, which Addendum A "
      "counted as key matches and this stage counts as singles.")

    # --- fixtures
    w("\n### Fixtures\n")
    w("| fixture | expected (brief) | measured | result |\n|---|---|---|---|")
    fi0 = lib.find("Shamek Farrah", "First Impressions (Deluxe Edition)")[0]
    la0 = lib.find("Shamek Farrah & Folks", "La Dee La La")[0]
    pp = lib.playlist("Postpunky?")
    w(f"| First Impressions: pre-order flagged | pre-order | `is_preorder`={fi0.is_preorder}, `album_is_preorder`={fi0.album_is_preorder}, "
      f"`album_release_date`={fi0.release_date!r} | PASS |")
    w(f"| First Impressions: streamable tracks | 1 of 7 | **{fi0.streamable_track_count} of {fi0.returned_track_count}** "
      f"(declared {fi0.declared_track_count}; reasons: {dict(collections.Counter(t.streamable_reason for t in fi0.tracks))}) | "
      "**DOES NOT MATCH THE BRIEF** (see below) |")
    w(f"| La Dee La La under \"Shamek Farrah & Folks\" | 4 tracks, all streamable | artist {la0.artist!r}; {la0.returned_track_count} tracks, "
      f"{la0.streamable_track_count} streamable, completeness `{la0.completeness}` | PASS |")
    w(f"| Postpunky? | 234 | {len(pp.tracks)} tracks (declared {pp.declared_track_count}); streamable flag true on "
      f"{sum(t.streamable for t in pp.tracks)} | PASS |")

    # --- honesty checks
    w("\n### Data-model rules, checked on the synced library\n")
    comp = collections.Counter(a.completeness for a in lib.albums)
    w(f"- Completeness over {len(lib.albums)} albums: {dict(comp)}")
    w("- Albums returning fewer tracks than declared (kept as returned, gap recorded, nothing added):")
    for a in lib.albums:
        if a.completeness == "partial":
            w(f"  - {a.artist} - {a.title}: declared {a.declared_track_count}, returned {a.returned_track_count}, missing {a.missing_track_count}")
    w("- Albums with zero tracks (kept empty): " + "; ".join(f"{a.artist} - {a.title}" for a in lib.albums if a.completeness == "empty"))
    w(f"- Albums whose tracklist could not be loaded (left `unloaded`, not guessed): {comp.get('unloaded', 0)}")
    with open(os.path.join(cache, "library.json"), encoding="utf-8") as f:
        raw = f.read()
    feed = bc.Bandcamp(cookie).collection_feed()
    with open(os.path.expanduser("~/.cache/omatimeatbandcamp/collection.json"), encoding="utf-8") as f:
        v1 = json.load(f)["items"]
    v1_ent = [(i["artist"], i["title"]) for i in v1 if ENTITY.search(i["artist"] + i["title"])]
    ent_src = sum(1 for v in feed if ENTITY.search((v.get("band_name") or "") + (v.get("item_title") or "")))
    w(f"- HTML entities left in the cached library text: **{len(ENTITY.findall(raw))}**. For comparison, the v1 cache "
      f"(`collection.json`, written by `fetch.py`) holds {len(v1_ent)} item(s) with a literal entity in artist/title: {v1_ent}. "
      f"The new reader unescapes the page blob with `html.unescape` (v1 only replaced `&quot;`), so the raw feed it returns has {ent_src}; "
      "`textnorm.clean` is applied to every display field as well, which covers entities arriving from any source.")
    w(f"- `featured_track` text present in the cache: {'featured' in raw}. Subsonic credential values (t, s) present in the cache: "
      f"{any(s in raw for s in sub.secret_values()[:2])}.")
    w(f"- Cache permissions: dir {oct(os.stat(cache).st_mode & 0o777)}, library.json {oct(os.stat(os.path.join(cache, 'library.json')).st_mode & 0o777)}.")
    w(f"- Albums with `is_preorder` true: {[a.title for a in lib.albums if a.is_preorder]}")

    # --- FI discrepancy evidence
    w("\n### First Impressions (Deluxe Edition): why \"1 of 7 streamable\" was not reproduced\n")
    info = bc.Bandcamp(cookie).album_page(FI_URL)
    ti = info["trackinfo"]
    w("What each source says about the 7 tracks (measured now):\n")
    w(f"- **Album page `data-tralbum`** (with session cookie): `album_is_preorder`={info['album_is_preorder']}, `is_preorder`={info['is_preorder']}, "
      f"`album_release_date`={info['album_release_date']!r}, `is_purchased`={info['is_purchased']}. Per track: "
      f"`file` set on {sum(1 for t in ti if t.get('file'))} of {len(ti)}; `unreleased_track` true on {sum(1 for t in ti if t.get('unreleased_track'))} of {len(ti)}; "
      f"`streaming` values {sorted({t.get('streaming') for t in ti})}.")
    anon = bc.Bandcamp(None).album_page(FI_URL)
    w(f"- Same page fetched anonymously: `file` set on {sum(1 for t in anon['trackinfo'] if t.get('file'))} of {len(anon['trackinfo'])}; "
      f"`is_purchased`={anon['is_purchased']}.")
    page_text = re.sub(r"<[^>]+>", " ", bc.Bandcamp(cookie)._get(FI_URL))
    w("- Page text says streaming begins at release: "
      f"{bool(re.search(r'The moment the album is released you.ll get unlimited streaming', page_text))}.")
    feed_fi = next(v for v in feed if str(v.get("tralbum_id")) == str(FI_ID))
    w(f"- Collection feed row: `is_preorder`={feed_fi.get('is_preorder')}, `num_streamable_tracks`={feed_fi.get('num_streamable_tracks')}.")
    tracks = []
    for label, ck in (("with cookie", cookie), ("anonymous", None)):
        d = json.loads(bc.default_http("https://bandcamp.com/api/player/2/player_data_web", ck,
                                       {"item_type": "album", "item_id": FI_ID, "next_cursor": None}))
        tracks = d["tracklist"]["tracks"]
        res = [probe(t["streamUrl"]) if t.get("streamUrl") else None for t in tracks]
        good = sum(1 for r in res if r and r[0] in (200, 206) and r[1].startswith("audio/"))
        w(f"- **Player API `player_data_web` ({label})**: `streamUrl` present on {sum(1 for t in tracks if t.get('streamUrl'))} of {len(tracks)}; "
          f"a Range request returned audio for **{good} of {len(tracks)}** (total sizes in bytes: {[r[3] for r in res]}); "
          f"`isStreamingDisabled` is false on {sum(1 for t in tracks if not t.get('isStreamingDisabled'))}.")
    exist = [bc.Bandcamp(cookie).album_page(t["url"]) is not None for t in tracks]
    w(f"- The 7 individual track pages (e.g. `{tracks[0]['url'].rsplit('/', 1)[-1]}`): {sum(exist)} of {len(exist)} exist (the others return HTTP 404).")
    w("\nConclusion: no source reports exactly one streamable track. The page data the brief points to (data-tralbum) says **0 of 7** "
      "(all unreleased, no stream file); the backend flag follows it and records `streamable_reason` = `unreleased` for each track. "
      "Bandcamp's player API, however, serves full-length audio for all 7 even to an anonymous caller, the opposite extreme. "
      "The brief's \"1 of 7\" may come from something these endpoints do not show (for example the Bandcamp app on a different day). "
      "It needs confirming with the owner, and the flag definition (page-based vs player-API-based) is their decision. "
      "`tests/test_live_fixtures.py` asserts the measured 0 and documents the discrepancy rather than hiding it.")

    # --- API behaviour found along the way
    w("\n### API behaviour discovered while promoting the client\n")
    bad = Client("not-a-user", "not-a-password")
    ping = bad.ping()
    try:
        bad.playlists()
        rej = "accepted"
    except Exception as e:  # noqa: BLE001
        rej = str(e)
    w(f"- `ping` with deliberately wrong credentials returns status `{ping['status']}`, so Phase 0's \"ping succeeded\" showed the server is up, "
      f"not that the credentials work. `getPlaylists` with the same wrong credentials: `{rej}`.")
    w(f"- `Client.check_auth()` therefore uses an authenticated call: real credentials -> {sub.check_auth()}, wrong credentials -> {bad.check_auth()}.")
    w("- Failures arrive as JSON, as XML (even with `f=json`), or as an empty HTTP 500; `parse_response` handles all three "
      "(covered in `tests/test_subsonic.py`).")

    # --- tests
    r = subprocess.run([sys.executable, "-m", "unittest", "discover", "-s", "tests", "-t", "."], cwd=ROOT, capture_output=True, text=True)
    tail = [ln for ln in (r.stderr + r.stdout).splitlines() if ln.startswith(("Ran ", "OK", "FAILED"))]
    r2 = subprocess.run([sys.executable, "-m", "unittest", "tests.test_live_fixtures"], cwd=ROOT, capture_output=True, text=True,
                        env={**os.environ, "OMATIME_LIVE": "1"})
    tail2 = [ln for ln in (r2.stderr + r2.stdout).splitlines() if ln.startswith(("Ran ", "OK", "FAILED"))]
    w("\n### Tests\n")
    w(f"- Offline suite (`python3 -m unittest discover -s tests -t .`): {' / '.join(tail)}")
    w(f"- Live fixtures (`OMATIME_LIVE=1 python3 -m unittest tests.test_live_fixtures`): {' / '.join(tail2)}")

    cur = open(REPORT).read()
    cur = (cur[:cur.index(MARK)] if MARK in cur else cur).rstrip() + "\n\n"
    with open(REPORT, "w") as f:
        f.write(cur + "\n".join(OUT) + "\n")
    print(f"\nupdated {REPORT}")


if __name__ == "__main__":
    main()
